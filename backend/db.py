"""PostgreSQL storage (SQLAlchemy 2.0 async + asyncpg) for users and chat history.

MANY WORKERS, ONE DATABASE - what this module does about it:
  * One engine (= one small connection pool) PER PROCESS, created lazily on the running event loop. Total connections the database must
    allow = workers x (DB_POOL_SIZE + DB_MAX_OVERFLOW). Defaults 2 x (5 + 5) = 20, far below Postgres' default max_connections = 100.
    Larger fleets: put PgBouncer (transaction mode) in front and set DB_PGBOUNCER=1 (turns off asyncpg's prepared-statement cache).
  * Start-up schema creation is serialised across workers with a Postgres advisory lock, so N workers booting together never race.
  * No state is kept in the process: every write is one short transaction, ids are generated by the database (identity columns / UUID
    from the application), user upsert is a single atomic INSERT .. ON CONFLICT, so two workers can never corrupt each other.
  * Stale or killed connections (database restart, idle timeouts, failover) are detected (pool_pre_ping), recycled (pool_recycle) and
    transient failures are retried with backoff. Every statement has a server-side timeout so a stuck query cannot pin a connection.
  * Pool exhaustion / database down surface as DatabaseUnavailable (see errors.py), never as a raw driver traceback.

Dialect notes: Postgres is the production database. The same code also runs on SQLite (aiosqlite) so the fast unit tests need no server;
that is why only the engine options and the advisory lock differ per dialect.
"""
import asyncio
import logging
import os
import time
import uuid

from sqlalchemy import (BigInteger, Float, Integer, ForeignKey, Identity, Index, MetaData, String, Text, delete, func, select, text, update)
from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.exc import DBAPIError, InterfaceError, OperationalError, SQLAlchemyError
from sqlalchemy.exc import TimeoutError as PoolTimeout
from sqlalchemy.ext.asyncio import AsyncEngine, async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from . import config

log = logging.getLogger("luma.db")

SCHEMA_LOCK_ID = 727_001            # arbitrary constant shared by every worker (pg_advisory_xact_lock key)


class DatabaseUnavailable(Exception):
    """The database cannot be used right now (down, pool exhausted, timeout). Details are in the log, not in the message."""


# ---------------------------------------------------------------------------------------------------- schema
class Base(DeclarativeBase):
    metadata = MetaData(naming_convention={"ix": "ix_%(column_0_label)s", "uq": "uq_%(table_name)s_%(column_0_name)s",
                                           "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s", "pk": "pk_%(table_name)s"})


class User(Base):
    __tablename__ = "users"
    email: Mapped[str] = mapped_column(String(320), primary_key=True)
    name: Mapped[str | None] = mapped_column(String(255))
    picture: Mapped[str | None] = mapped_column(Text)
    created: Mapped[float] = mapped_column(Float, nullable=False)
    last_login: Mapped[float] = mapped_column(Float, nullable=False)


class Conversation(Base):
    __tablename__ = "conversations"
    id: Mapped[str] = mapped_column(String(32), primary_key=True)
    user_email: Mapped[str] = mapped_column(String(320), ForeignKey("users.email", ondelete="CASCADE"), nullable=False)
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    created: Mapped[float] = mapped_column(Float, nullable=False)
    updated: Mapped[float] = mapped_column(Float, nullable=False)
    __table_args__ = (Index("idx_conv_user", "user_email", "updated"),)


class Message(Base):
    __tablename__ = "messages"
    id: Mapped[int] = mapped_column(BigInteger().with_variant(Integer, "sqlite"), Identity(always=False), primary_key=True)
    conversation_id: Mapped[str] = mapped_column(String(32), ForeignKey("conversations.id", ondelete="CASCADE"), nullable=False)
    role: Mapped[str] = mapped_column(String(16), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    created: Mapped[float] = mapped_column(Float, nullable=False)
    __table_args__ = (Index("idx_msg_conv", "conversation_id", "id"),)


# ---------------------------------------------------------------------------------------------------- engine (one per process / loop)
_engine: AsyncEngine | None = None
_engine_loop = None
_sessions: async_sessionmaker | None = None


def _url() -> str:
    url = config.DATABASE_URL
    if url.startswith("postgres://"):
        url = "postgresql+asyncpg://" + url[len("postgres://"):]
    elif url.startswith("postgresql://"):
        url = "postgresql+asyncpg://" + url[len("postgresql://"):]
    return url


def _is_pg() -> bool:
    return _url().startswith("postgresql")


def _make_engine() -> AsyncEngine:
    url = _url()
    if url.startswith("sqlite"):
        if "///" in url and ":memory:" not in url:
            os.makedirs(os.path.dirname(url.split("///", 1)[1]) or ".", exist_ok=True)
        return create_async_engine(url)
    connect_args = {
        "timeout": config.DB_CONNECT_TIMEOUT,                       # seconds to open a connection
        "command_timeout": config.DB_COMMAND_TIMEOUT,               # client side per-statement timeout
        "server_settings": {
            "application_name": f"luma-{os.getpid()}",              # shows in pg_stat_activity: which worker holds which connection
            "statement_timeout": str(int(config.DB_STATEMENT_TIMEOUT_MS)),
            "idle_in_transaction_session_timeout": str(int(config.DB_IDLE_TX_TIMEOUT_MS)),   # a crashed worker's open transaction is rolled back
            "lock_timeout": "5000",
        },
    }
    if config.DB_PGBOUNCER:
        connect_args["statement_cache_size"] = 0                    # PgBouncer in transaction mode cannot keep prepared statements
        connect_args["prepared_statement_cache_size"] = 0
    return create_async_engine(
        url, pool_size=config.DB_POOL_SIZE, max_overflow=config.DB_MAX_OVERFLOW, pool_timeout=config.DB_POOL_TIMEOUT,
        pool_recycle=config.DB_POOL_RECYCLE, pool_pre_ping=True, connect_args=connect_args)


def engine() -> AsyncEngine:
    """The engine of the running event loop. (uvicorn: one loop per worker, so one engine per worker. Test clients with several loops get
    one engine per loop: asyncpg connections cannot be shared between event loops.)"""
    global _engine, _engine_loop, _sessions
    loop = asyncio.get_running_loop()
    if _engine is None or _engine_loop is not loop:
        if _engine is not None:
            _engine.sync_engine.dispose(close=False)                # the old loop is gone: drop its connections without awaiting them
        _engine, _engine_loop = _make_engine(), loop
        _sessions = async_sessionmaker(_engine, expire_on_commit=False)
    return _engine


def sessions() -> async_sessionmaker:
    engine()
    return _sessions


async def dispose() -> None:
    global _engine, _engine_loop, _sessions
    e, _engine, _engine_loop, _sessions = _engine, None, None, None
    if e is not None:
        await e.dispose()


async def init_db() -> None:
    """Create the tables if they do not exist. Safe with any number of workers starting at the same moment."""
    async with engine().begin() as conn:
        if _is_pg():
            await conn.execute(text("SELECT pg_advisory_xact_lock(:k)"), {"k": SCHEMA_LOCK_ID})      # held until this transaction ends
        await conn.run_sync(Base.metadata.create_all)


async def ping() -> bool:
    try:
        async with sessions()() as s:
            await asyncio.wait_for(s.execute(text("SELECT 1")), 3)
        return True
    except Exception:
        return False


async def pool_status() -> dict:
    p = engine().pool
    try:
        return {"size": p.size(), "checked_out": p.checkedout(), "overflow": p.overflow()}
    except Exception:
        return {}


# ---------------------------------------------------------------------------------------------------- retry wrapper
_TRANSIENT_SQLSTATES = {"40001", "40P01", "08000", "08003", "08006", "57P01", "57P02", "57P03", "53300"}   # serialization, deadlock, connection, shutdown, too many


def _transient(exc: BaseException) -> bool:
    if isinstance(exc, (InterfaceError, ConnectionError, asyncio.TimeoutError, PoolTimeout)):
        return True
    if isinstance(exc, OperationalError):
        return True
    orig = getattr(exc, "orig", None)
    code = getattr(orig, "sqlstate", None) or getattr(orig, "pgcode", None)
    return bool(code and code in _TRANSIENT_SQLSTATES)


async def _run(op):
    """Run `op(session)` in ONE transaction; retry transient failures (restarting database, dropped connection, deadlock) with backoff."""
    last: Exception | None = None
    for attempt in range(config.DB_RETRIES + 1):
        try:
            async with sessions()() as s:
                async with s.begin():
                    return await op(s)
        except (SQLAlchemyError, ConnectionError, asyncio.TimeoutError, OSError) as exc:
            last = exc
            if attempt < config.DB_RETRIES and _transient(exc):
                await asyncio.sleep(config.DB_RETRY_BASE_SECONDS * (2 ** attempt) * (0.5 + 0.5 * (time.time() % 1)))
                continue
            break
    log.warning("database call failed: %s: %s", type(last).__name__, str(last)[:200])
    if isinstance(last, DBAPIError) and not _transient(last):
        raise last                                                   # a real SQL/data error: a bug, not an outage
    raise DatabaseUnavailable(f"{type(last).__name__}") from last


def _upsert(model):
    return (postgresql.insert if _is_pg() else sqlite.insert)(model)


def _row(obj, *cols) -> dict:
    return {c: getattr(obj, c) for c in cols}


# ---------------------------------------------------------------------------------------------------- users
async def upsert_user(email: str, name: str, picture: str) -> dict:
    now = time.time()

    async def op(s):
        stmt = _upsert(User).values(email=email, name=name, picture=picture, created=now, last_login=now)
        stmt = stmt.on_conflict_do_update(index_elements=[User.email], set_={"name": stmt.excluded.name, "picture": stmt.excluded.picture,
                                                                            "last_login": stmt.excluded.last_login})
        await s.execute(stmt)                                       # atomic: two workers logging in the same student cannot conflict
        return {"email": email, "name": name, "picture": picture}

    return await _run(op)


async def get_user(email: str) -> dict | None:
    async def op(s):
        u = (await s.execute(select(User).where(User.email == email))).scalar_one_or_none()
        return _row(u, "email", "name", "picture") if u else None
    return await _run(op)


# ---------------------------------------------------------------------------------------------------- conversations
async def create_conversation(email: str, title: str) -> str:
    cid, now = uuid.uuid4().hex, time.time()

    async def op(s):
        s.add(Conversation(id=cid, user_email=email, title=title, created=now, updated=now))
        return cid
    return await _run(op)


async def list_conversations(email: str) -> list[dict]:
    async def op(s):
        rows = (await s.execute(select(Conversation).where(Conversation.user_email == email)
                                .order_by(Conversation.updated.desc()).limit(200))).scalars().all()
        return [_row(c, "id", "title", "updated") for c in rows]
    return await _run(op)


async def get_conversation(email: str, cid: str) -> dict | None:
    """Returns the conversation only if it belongs to this user."""
    async def op(s):
        c = (await s.execute(select(Conversation).where(Conversation.id == cid, Conversation.user_email == email))).scalar_one_or_none()
        return _row(c, "id", "title", "updated") if c else None
    return await _run(op)


async def rename_conversation(email: str, cid: str, title: str) -> bool:
    async def op(s):
        r = await s.execute(update(Conversation).where(Conversation.id == cid, Conversation.user_email == email).values(title=title))
        return r.rowcount > 0
    return await _run(op)


async def delete_conversation(email: str, cid: str) -> bool:
    async def op(s):
        r = await s.execute(delete(Conversation).where(Conversation.id == cid, Conversation.user_email == email))
        return r.rowcount > 0
    return await _run(op)


# ---------------------------------------------------------------------------------------------------- messages
async def add_message(cid: str, role: str, content: str) -> None:
    now = time.time()

    async def op(s):
        s.add(Message(conversation_id=cid, role=role, content=content, created=now))
        await s.execute(update(Conversation).where(Conversation.id == cid).values(updated=now))       # same transaction: never half saved
    await _run(op)


async def get_messages(cid: str, limit: int | None = None) -> list[dict]:
    async def op(s):
        q = select(Message).where(Message.conversation_id == cid)
        if limit:
            rows = (await s.execute(q.order_by(Message.id.desc()).limit(limit))).scalars().all()[::-1]
        else:
            rows = (await s.execute(q.order_by(Message.id))).scalars().all()
        return [{"role": m.role, "content": m.content} for m in rows]
    return await _run(op)


async def count_messages(cid: str) -> int:
    async def op(s):
        return (await s.execute(select(func.count()).select_from(Message).where(Message.conversation_id == cid))).scalar_one()
    return await _run(op)

